def run_query_with_langchain(query: str) -> dict:
    """
    Executes a Cypher query using LangChain's GraphCypherQAChain and returns the formatted results.
    """
    # Step 1: Run the Cypher query generated by the LLM
    raw_result = cypher_qa.invoke(query)
    
    # Debugging: Print the raw result to check its type
    print(f"Raw Result: {raw_result} (type: {type(raw_result)})")
    
    # Step 2: Check if raw_result is a string and handle it
    if isinstance(raw_result, str):
        # Return the raw string message if it's not a dictionary
        return {"message": raw_result}
    
    # Step 3: Format the raw result if it's a dictionary
    formatted_result = format_result(raw_result)
    
    return formatted_result


