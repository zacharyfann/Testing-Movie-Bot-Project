def format_result(result) -> dict:
    """
    Formats Neo4j query results into a structure that's easy for LLMs to interpret.
    Handles nodes, relationships, lists, and properties.
    """
    # Check if the result is a string
    if isinstance(result, str):
        # If it's a string, return it as is
        return {"message": result}
    
    formatted_result = {}
    
    for key, value in result.items():
        if isinstance(value, dict):
            # If it's already a dictionary, return it as is
            formatted_result[key] = value
        elif isinstance(value, list):
            # If it's a list, format each item in the list
            formatted_result[key] = [format_entity(item) for item in value]
        else:
            # Format single entities (nodes, relationships, etc.)
            formatted_result[key] = format_entity(value)
    
    return formatted_result


def format_entity(entity):
    """
    Formats Neo4j entities (nodes, relationships, etc.) into a dictionary structure.
    """
    if hasattr(entity, "labels"):
        # It's a node
        return {
            "type": "node",
            "labels": list(entity.labels),
            "properties": dict(entity)
        }
    elif hasattr(entity, "type"):
        # It's a relationship
        return {
            "type": "relationship",
            "relationship_type": entity.type,
            "properties": dict(entity)
        }
    else:
        # It's a scalar value (e.g., string, number, etc.)
        return entity



